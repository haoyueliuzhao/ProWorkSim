def run_case(name, output):
    output = Path(output)
    output.mkdir(parents=True, exist_ok=True)
    ev, error, outcome = Evidence(name, output), None, None
    try:
        outcome = execute(ev)
    except Exception:
        error = traceback.format_exc()
    for name_ in CHECKS:
        if not any(c["name"] == name_ for c in ev.checks):
            ev.checks.append({"name": name_, "passed": False, "not_executed": True})
    result = {
        "case": name,
        "construction_error": error,
        "checks": ev.checks,
        "passed": error is None and all(c["passed"] for c in ev.checks),
        "outcome": outcome,
        "controller_calls": ev.calls,
        "captures": ev.captures,
        "worker_transcripts": {label: worker.transcript for label, worker in ev.workers.items()},
        "evaluations": ev.evaluations,
    }
    if ev.world:
        write_json(output / "final-state.json", ev.state())
        result["immutable_file_sha256"] = ev.hashes()
    write_json(output / "report.json", result)
    return result


def run(output, workers=3):
    output = Path(output)
    output.mkdir(parents=True, exist_ok=False)
    before, started = code_identity(), datetime.now(timezone.utc).isoformat()
    write_json(output / "protocol.json", PROTOCOL)
    with ThreadPoolExecutor(max_workers=workers) as pool:
        cases = list(pool.map(lambda name: run_case(name, output / name), CASES))
    report = {
        "source_before": before,
        "source_after": code_identity(),
        "started_at": started,
        "ended_at": datetime.now(timezone.utc).isoformat(),
        "protocol": PROTOCOL,
        "cases": cases,
        "passed_cases": sum(c["passed"] for c in cases),
        "passed_checks": sum(c["passed"] for r in cases for c in r["checks"]),
        "total_checks": len(CASES) * len(CHECKS),
        "not_executed": sum(c["not_executed"] for r in cases for c in r["checks"]),
        "passed": all(c["passed"] for c in cases),
    }
    write_json(output / "report.json", report)
    return report


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--workers", type=int, default=3)
    args = parser.parse_args()
    result = run(args.output, args.workers)
