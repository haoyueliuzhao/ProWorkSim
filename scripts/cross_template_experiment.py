def normalized_trace(transcript):
    result = []
    for event in transcript:
        if event["kind"] == "call":
            result.append(
                {
                    "kind": "call",
                    "action": event["action"],
                    "arguments": event["arguments"],
                    "result": event.get("result", event.get("response")),
                }
            )
        else:
            result.append(
                {
                    "kind": "observe"
                    if event["kind"] in {"observe", "observation"}
                    else event["kind"],
                    "result": event.get("result", event.get("value")),
                }
            )
    return result


class PublicReportContinuation:
    """Public-only scheduling bridge; expected answers are never arguments."""

    def __init__(self, author, reviewer):
        self.author, self.reviewer = author, reviewer

    def deliver(self, work_id=None, *, inject_body_error=False):
        observation = self.author.observe()
        if work_id is None:
            candidates = [
                wid
                for wid, item in observation["work_items"].items()
                if item.get("submission_state") != "accepted"
                and item.get("status") not in {"accepted", "superseded"}
                and any(
                    s.get("kind") == "research_report"
                    for s in item["deliverable_contract"]["content_checks"]
                )
            ]
            if len(candidates) != 1:
                raise ValueError("Expected one publicly discoverable report obligation")
            work_id = candidates[0]
        work = observation["work_items"][work_id]
        requirement = work["requirements"]
        alias, oid = "comparison", requirement["source_objects"]["comparison"]
        if requirement["input_policy"] == "fixed":
            version = requirement["input_version"]
        else:
            version = [
                r["version_id"] for r in observation["publications"] if r["object_id"] == oid
            ][-1]
        if work_id + "::" + alias not in observation["adoptions"]:
            self.author.call(
                "adopt",
                alias=alias,
                object_id=oid,
                version_id=version,
                policy=requirement["input_policy"],
                work_ids=[work_id],
            )
        report_alias = requirement["output_alias"]
        data, refs = self.author.prepare(
            work_id,
            report_alias=report_alias,
            defects={"conflicts": "body_number"} if inject_body_error else None,
        )
        sub = self.author.deliver(work_id, data, refs, report_alias=report_alias)
        findings = self.reviewer.review(work_id, sub["submission_id"])
        return {
            "work_id": work_id,
            "submission": sub,
            "findings": findings,
            "data": data,
            "source_version": version,
        }

    def review_and_finish(self, delivered):
        wid, sub, findings = delivered["work_id"], delivered["submission"], delivered["findings"]
        issues = self.reviewer.raise_findings(wid, sub["submission_id"], findings)
        if issues:
            self.author.call(
                "withdraw",
                work_id=wid,
                submission_id=sub["submission_id"],
                reason="Repair the located actual body under unchanged requirements",
            )
            alias = self.author.observe()["work_items"][wid]["requirements"]["output_alias"]
            data, refs = self.author.prepare(
                wid, report_alias=alias, fix_claims={f["claim_id"] for f in findings}
            )
            sub = self.author.deliver(wid, data, refs, report_alias=alias)
            if self.reviewer.review(wid, sub["submission_id"]):
                raise ValueError("Finite public review still finds an unrepaired assertion")
            for issue in issues:
                response = self.author.call(
                    "respond_issue",
                    issue_id=issue["issue_id"],
                    response_key="correct-" + sub["submission_id"],
                    submission_id=sub["submission_id"],
                    body="Corrected only the located assertion using the actual adopted source",
                    evidence=refs,
                )
                self.reviewer.call(
                    "decide_issue",
                    issue_id=issue["issue_id"],
                    response_id=response["response_id"],
                    decision_key="verify-" + response["response_id"],
                    decision="accept_fix",
                    reason="Actual new body and exact source have been read and agree",
                )
        self.reviewer.call("approve", work_id=wid, submission_id=sub["submission_id"])
        return sub, issues


class Evidence:
    def __init__(self, name, output):
        self.name, self.output = name, Path(output)
        self.calls, self.checks, self.evaluations, self.captures = [], [], [], {}
        self.world = None
        self.workers = {}

    def call(self, actor, project, action, **arguments):
        response = self.world.session(actor, project).call(action, **arguments)
        self.calls.append(
            {
                "actor": actor,
                "project": project,
                "action": action,
                "arguments": copy.deepcopy(arguments),
                "result": copy.deepcopy(response),
            }
        )
        if not response.get("ok"):
            raise AssertionError(response)
        return response["result"]

    def port(self, actor, project, label):
        session, capture = self.world.session(actor, project), self.captures.setdefault(label, [])

        class Port:
            __slots__ = ()

            def tools(self):
                result = session.tools()
                capture.append({"kind": "tools", "result": copy.deepcopy(result)})
                return result

            def observe(self):
                result = session.observe()
                capture.append({"kind": "observe", "result": copy.deepcopy(result)})
                return result

            def call(self, action, **arguments):
                result = session.call(action, **arguments)
                capture.append(
                    {
                        "kind": "call",
                        "action": action,
                        "arguments": copy.deepcopy(arguments),
                        "result": copy.deepcopy(result),
                    }
                )
                return result

        return Port()

    def state(self):
        return self.world.store.load()

    def check(self, name, observed, expected=True):
        assert name in CHECKS and not any(c["name"] == name for c in self.checks)
        self.checks.append(
            {
                "name": name,
                "observed": copy.deepcopy(observed),
                "expected": copy.deepcopy(expected),
                "passed": observed == expected,
                "not_executed": False,
            }
        )

    def evaluate(self, project, work, sub):
        result = self.world.evaluate_submission(project, work, sub["submission_id"])
        self.evaluations.append(
            {
                "project": project,
                "work_id": work,
                "submission_id": sub["submission_id"],
                "result": copy.deepcopy(result),
            }
        )
        return result

    def hashes(self, project=None):
        return {
            oid + "/" + vid: digest(self.world.store.version_path(obj, vid).read_bytes())
            for oid, obj in self.state()["artifacts"].items()
            if project is None or obj["project_id"] == project
            for vid in obj["versions"]
        }


def facts(data):
    return {
        section["section_id"]: section["claims"][0]
        for section in data["report"]["sections"]
        if section.get("claims")
    }


def responsibilities(a_eval, b_eval, data, interface):
    values = facts(data)
    faithful = (
        values["conflicts"]["value"] == interface["reconciliation"]["summary"]["conflict"]
        and values["incomparable"]["value"]
        == interface["reconciliation"]["summary"]["incomparable"]
        and all(v["period"] == interface["reconciliation"]["period"] for v in values.values())
    )
    expression = (
        all(
            d["body_correct"] and d["metadata_correct"]
            for c in b_eval["checks"]
            for d in c.get("diagnostics", [])
        )
        and b_eval["passed"]
    )
    return {
        "A_quality": a_eval["passed"],
        "B_interface_fidelity": faithful,
        "B_expression": expression,
        "overall_goal": values["conflicts"]["value"] == 0
        and values["incomparable"]["value"] == 3
        and expression,
    }


